import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const unicodeVersion = "17.0.0";
const sourceUrl = `https://www.unicode.org/Public/${unicodeVersion}/ucd/VerticalOrientation.txt`;
const outputUrl = new URL("../src/pipeline/typeset/verticalOrientationData.ts", import.meta.url);
const valueCodes = new Map([
  ["R", 0],
  ["U", 1],
  ["Tu", 2],
  ["Tr", 3],
]);

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(`Failed to download ${sourceUrl}: HTTP ${response.status}`);
}

const source = await response.text();
const records = [];
for (const line of source.split(/\r?\n/)) {
  const match = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(U|R|Tu|Tr)\b/.exec(line);
  if (!match) continue;
  const start = Number.parseInt(match[1], 16);
  const end = Number.parseInt(match[2] ?? match[1], 16);
  const value = valueCodes.get(match[3]);
  if (value === undefined) {
    throw new Error(`Unsupported Vertical_Orientation value: ${match[3]}`);
  }
  const previous = records.at(-1);
  if (previous && previous[2] === value && start <= previous[1] + 1) {
    previous[1] = Math.max(previous[1], end);
  } else {
    records.push([start, end, value]);
  }
}

const rows = records.map(([start, end, value]) =>
  `  [0x${start.toString(16).toUpperCase()}, 0x${end.toString(16).toUpperCase()}, ${value}],`,
);
const output = `// Generated by scripts/generate-vertical-orientation.mjs. Do not edit manually.\n`
  + `// Source: ${sourceUrl}\n`
  + `// Unicode Terms of Use: https://www.unicode.org/terms_of_use.html\n\n`
  + `export const verticalOrientationUnicodeVersion = "${unicodeVersion}";\n\n`
  + `// Value codes: 0=R, 1=U, 2=Tu, 3=Tr. Missing assigned characters fall back to R.\n`
  + `export const verticalOrientationRanges: readonly (readonly [number, number, number])[] = [\n`
  + `${rows.join("\n")}\n`
  + `];\n`;

await writeFile(outputUrl, output, "utf8");
console.log(`Generated ${records.length} ranges at ${fileURLToPath(outputUrl)}`);
